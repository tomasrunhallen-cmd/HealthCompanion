#!/usr/bin/env node
// Bundles prompts/*.md and schemas/*.json into a generated TypeScript module so the app can
// load them at runtime without file access. The markdown files stay the source of truth;
// no prompt text is written by hand in the code.
const fs = require('node:fs');
const path = require('node:path');

const root = path.join(__dirname, '..');
const out = path.join(root, 'src', 'prompts', 'bundle.generated.ts');

function readDir(dir, ext) {
  const full = path.join(root, dir);
  return fs
    .readdirSync(full)
    .filter((f) => f.endsWith(ext))
    .sort()
    .map((f) => ({ name: `${dir}/${f}`, content: fs.readFileSync(path.join(full, f), 'utf8') }));
}

const prompts = readDir('prompts', '.md');
const schemas = readDir('schemas', '.json');
// context/: standard content and the emergency word list. App data, not prompts: never
// sent to a model as such.
const context = readDir('context', '.md');

const lines = [
  '// GENERATED by scripts/build-prompts.js from prompts/ and schemas/. Do not edit by hand.',
  '/* eslint-disable */',
  'export const PROMPT_SOURCES: Record<string, string> = {',
  ...prompts.map((p) => `  ${JSON.stringify(p.name)}: ${JSON.stringify(p.content)},`),
  '};',
  '',
  'export const SCHEMA_SOURCES: Record<string, unknown> = {',
  ...schemas.map((s) => `  ${JSON.stringify(s.name)}: ${JSON.stringify(JSON.parse(s.content))},`),
  '};',
  '',
  'export const CONTEXT_SOURCES: Record<string, string> = {',
  ...context.map((c) => `  ${JSON.stringify(c.name)}: ${JSON.stringify(c.content)},`),
  '};',
  '',
];

const next = lines.join('\n');
const prev = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : '';
if (prev !== next) {
  fs.writeFileSync(out, next);
  console.log(`build-prompts: wrote ${path.relative(root, out)} (${prompts.length} prompts, ${schemas.length} schemas, ${context.length} context files)`);
}
